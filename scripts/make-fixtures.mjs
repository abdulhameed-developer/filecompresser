/**
 * Build real test fixtures on disk for browser-level QA.
 *
 * The archive fixtures are genuine ZIP byte structures (built with fflate),
 * not stubs, so what the browser UI extracts is exactly what a user would get
 * from a real download.
 *
 *   node scripts/make-fixtures.mjs [outDir]
 */

import { zipSync } from 'fflate'
import { writeFileSync, mkdirSync, copyFileSync, existsSync, readFileSync } from 'node:fs'
import path from 'node:path'

const out = process.argv[2] || path.join(process.cwd(), '.qa-fixtures')
mkdirSync(out, { recursive: true })

const text = (s) => new TextEncoder().encode(s)

const fixtures = {
  // Path traversal, hidden behind a plausible folder name.
  'traversal.zip': zipSync({
    'photos/../../../../root/.ssh/authorized_keys': text('pwned'),
    'notes.txt': text('this entry is safe'),
  }, { level: 0 }),

  // Absolute path and a Windows drive letter in one archive.
  'absolute.zip': zipSync({
    '/etc/shadow': text('root:x:0:0'),
    'C:\\Windows\\System32\\evil.dll': text('MZ'),
  }, { level: 0 }),

  // A perfectly normal archive, to prove the guards are not over-blocking.
  'normal.zip': zipSync({
    'readme.txt': text('hello from a normal archive'),
    'data/values.csv': text('a,b,c\n1,2,3\n'),
  }, { level: 6 }),

  // A file that is not a ZIP at all, wearing a .zip extension.
  'not-really.zip': text('this is plain text pretending to be an archive'),
}

for (const [name, bytes] of Object.entries(fixtures)) {
  const file = path.join(out, name)
  writeFileSync(file, bytes)
  console.log(`${name}  ${bytes.length} bytes`)
}

// A real three-page PDF, so the PDF compressor and PDF->JPG routes are
// exercised against genuine document bytes rather than a stub.
const { PDFDocument } = await import('pdf-lib')
const pdf = await PDFDocument.create()
pdf.setTitle('QA Fixture Document')
pdf.setAuthor('filecompresser QA')
for (let i = 1; i <= 3; i++) {
  const page = pdf.addPage([595, 842])
  page.drawText(`Sample page ${i}`, { x: 60, y: 760, size: 22 })
}
const pdfBytes = await pdf.save()
writeFileSync(path.join(out, 'sample.pdf'), pdfBytes)
console.log(`sample.pdf  ${pdfBytes.length} bytes`)

/**
 * A real 16-bit mono PCM WAV, built byte by byte. Exercises the audio engine
 * against genuine container bytes rather than a stub, and WAV is the one audio
 * input format the app can produce without an external encoder.
 */
function makeWav(seconds = 1, sampleRate = 8000) {
  const samples = seconds * sampleRate
  const dataSize = samples * 2 // 16-bit mono
  const buf = new ArrayBuffer(44 + dataSize)
  const view = new DataView(buf)
  const ascii = (offset, s) => {
    for (let i = 0; i < s.length; i++) view.setUint8(offset + i, s.charCodeAt(i))
  }
  ascii(0, 'RIFF')
  view.setUint32(4, 36 + dataSize, true)
  ascii(8, 'WAVE')
  ascii(12, 'fmt ')
  view.setUint32(16, 16, true) // PCM chunk size
  view.setUint16(20, 1, true) // format = PCM
  view.setUint16(22, 1, true) // channels = mono
  view.setUint32(24, sampleRate, true)
  view.setUint32(28, sampleRate * 2, true) // byte rate
  view.setUint16(32, 2, true) // block align
  view.setUint16(34, 16, true) // bits per sample
  ascii(36, 'data')
  view.setUint32(40, dataSize, true)
  // A 440 Hz tone, so the encoder has real signal to work on.
  for (let i = 0; i < samples; i++) {
    const value = Math.sin((2 * Math.PI * 440 * i) / sampleRate) * 12000
    view.setInt16(44 + i * 2, value, true)
  }
  return new Uint8Array(buf)
}

const wav = makeWav(2)
writeFileSync(path.join(out, 'tone.wav'), wav)
console.log(`tone.wav  ${wav.length} bytes`)

/**
 * The GIF fixture is produced by `scripts/make-gif.mjs`, which uses `omggif`
 * for the LZW stream. A hand-rolled encoder is easy to get subtly wrong, and a
 * malformed GIF then fails deep inside FFmpeg — indistinguishable from an
 * application bug.
 */
if (existsSync(path.join(out, 'anim.gif'))) {
  const size = readFileSync(path.join(out, 'anim.gif')).length
  console.log(`anim.gif  ${size} bytes (generated by make-gif.mjs)`)
}

/**
 * Copy the fixtures into `public/` so the running server can serve them to the
 * browser-driven QA scripts. They are test assets, not site content — remove
 * them from `public/` before shipping.
 */
const publicDir = path.join(process.cwd(), 'public')
if (existsSync(publicDir) && process.env.COPY_TO_PUBLIC !== '0') {
  for (const name of Object.keys(fixtures).concat(['sample.pdf', 'tone.wav', 'anim.gif'])) {
    copyFileSync(path.join(out, name), path.join(publicDir, name))
  }
  console.log(`\ncopied fixtures into public/ (QA only — not for shipping)`)
}

console.log(`\nwritten to ${out}`)