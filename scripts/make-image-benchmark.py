def serializable(value):
    if isinstance(value, dict): return {k: serializable(v) for k,v in value.items()}
    if isinstance(value, list): return [serializable(v) for v in value]
    if isinstance(value, (bytes, bytearray)): return {"byteLength": len(value), "sha256": hashlib.sha256(value).hexdigest()}
    if isinstance(value, Image.Exif): return {str(k): v for k,v in value.items()}
    return value
(root/"manifest.json").write_text(json.dumps(serializable({"version":1, "environment": {"python": platform.python_version(), "pillow": pillow_version}, "sources": [
    {"file": "sources/portrait.jpg", "url": "https://upload.wikimedia.org/wikipedia/commons/8/8d/President_Barack_Obama.jpg", "sha256": hashlib.sha256((root/"sources/portrait.jpg").read_bytes()).hexdigest()},
    {"file": "sources/landscape.jpg", "url": "https://thumb.wikimedia.org/wikipedia/commons/thumb/3/3f/Fronalpstock_big.jpg/3840px-Fronalpstock_big.jpg", "sha256": hashlib.sha256((root/"sources/landscape.jpg").read_bytes()).hexdigest()}
], "fixtures":records}), indent=2)+"\n")
for r in records: print(f"{r['file']} {r['bytes']} bytes {r['displayDimensions']}")
