"""Create deterministic public/own-work fixtures, never user images.

Usage: python scripts/make-image-benchmark.py OUTPUT_DIRECTORY
Pre-download portrait.jpg and landscape.jpg into OUTPUT_DIRECTORY/sources/.
Those exact source URLs, rights and derivatives are recorded in manifest.json.
The fixture-generation resampling defines input files only; processing must keep
each resulting fixture's dimensions unchanged.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageCms, __version__ as pillow_version
import hashlib
import json
import math
import sys
import platform

root = Path(sys.argv[1])
out = root / "inputs"
if (root / "manifest.json").exists():
    raise SystemExit("This dataset already has a manifest. Use a new output directory to preserve measured inputs.")
out.mkdir(parents=True, exist_ok=True)
font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
font = ImageFont.truetype(font_path, 24)
small = ImageFont.truetype(font_path, 17)
title = ImageFont.truetype(font_path, 40)
records = []

def save(image, name, category, license="CC0-1.0", attribution="Generated by FileCompresser benchmark script", source=None, **options):
    target = out / name
    image.save(target, **options)
    with Image.open(target) as opened:
        display = opened.size[::-1] if opened.getexif().get(274) in [5, 6, 7, 8] else opened.size
        fixture_id = target.stem + ("-webp" if target.suffix == ".webp" else "")
        records.append({"id": fixture_id, "file": name, "category": category, "bytes": target.stat().st_size,
                        "sha256": hashlib.sha256(target.read_bytes()).hexdigest(), "format": opened.format,
                        "storedDimensions": list(opened.size), "displayDimensions": list(display), "mode": opened.mode,
                        "license": license, "attribution": attribution, "source": source,
                        "generation": options | {"exif": "orientation 6"} if options.get("exif") else options})

